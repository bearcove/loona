/// `repeats` repetitions of the 8-symbol string "aaaaaaaa" (5 bytes when
/// Huffman-coded), sent as the value of a literal with indexed name 1.
fn long_huffman_value(repeats: usize) -> Vec<u8> {
    let mut value = Vec::with_capacity(repeats * 5);
    for _ in 0..repeats {
        value.extend_from_slice(&[0x18, 0xc6, 0x31, 0x8c, 0x63]);
    }
    // Literal without indexing, name index 1, Huffman value length (7-bit prefix).
    let mut block = vec![0x01, 0xff];
    let mut rest = value.len() - 127;
    while rest >= 0x80 {
        block.push(0x80 | (rest & 0x7f) as u8);
        rest >>= 7;
    }
    block.push(rest as u8);
    block.extend_from_slice(&value);
    block
}

pub fn decode(c: &mut Criterion) {
    // 1024 fields: name index 1 with a 1-byte Huffman value ("0").
    let many_small = [0x01u8, 0x81, 0x07].repeat(1024);
    let long_value = long_huffman_value(13_000);

    let mut c = c.benchmark_group("hpack_decode");

    c.bench_function("typical_request", |b| {
        b.iter(|| {
            let mut decoder = Decoder::new();
            black_box(decoder.decode(black_box(TYPICAL_REQUEST)).unwrap());
        })
    });

    c.bench_function("1024_small_huffman_values", |b| {
        b.iter(|| {
            let mut decoder = Decoder::new();
            black_box(decoder.decode(black_box(&many_small)).unwrap());
        })
    });

    c.bench_function("one_64k_huffman_value", |b| {
        b.iter(|| {
            let mut decoder = Decoder::new();
            black_box(decoder.decode(black_box(&long_value)).unwrap());
        })
    });

    c.finish();
}

criterion_group!(benches, decode);
criterion_main!(benches);
